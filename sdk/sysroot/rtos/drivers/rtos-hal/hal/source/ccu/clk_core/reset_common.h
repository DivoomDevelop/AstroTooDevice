#ifndef __RESET_COMMON_H__
#define __RESET_COMMON_H__

#include "clk_common.h"

#define rst_udelay hal_udelay

typedef clk_controller_id_t rst_controller_id_t;
typedef uint16_t rst_id_t;

typedef uint32_t rst_number_t;

typedef void *hal_rst_t;

#define RC_ID_BITS CC_ID_BITS
#define RC_ID_MASK ((1U << RC_ID_BITS) - 1)
#define RST_ID_BITS 16
#define RST_ID_MASK ((1U << RST_ID_BITS) - 1)

#define RC_ID(rst_number)  ((unsigned int)(((rst_number) >> RST_ID_BITS) & RC_ID_MASK))
#define RST_ID(rst_number)  ((unsigned int)((rst_number) & RST_ID_MASK))
#define MAKE_RSTn(rc_id, rst_id) (((rc_id) << RST_ID_BITS) | (rst_id))

#define MAX_RC_ID (RC_ID_MASK - 1)
#define MAX_RST_ID (RST_ID_MASK - 1)

#define INVALID_RC_ID INVALID_CC_ID
#define INVALID_RST_ID -1
#define INVALID_RST_NUM -1

#endif /* __RESET_COMMON_H__ */

