#ifndef	__SYSCFG_SUN251IW1_H_
#define	__SYSCFG_SUN251IW1_H_

#define	SUNXI_SYSCFG_MEMBASE (0x03000000)

/*------------------SYSCFG AUDIO register definition--------------------*/
#define	SUNXI_AUDIO_PATH_HDMIRX_CTRL		0x0190

/* SUNXI_AUDIO_PATH_HDMIRX_CTRL register */
#define	OWA_TX_TO_HDMIRX_EN		9
#define	OWA_TX_TO_GPIO_EN		8
#define	OWA_RX_SRC_SEL		    4
#define I2S_RX_SRC_SEL		    0

#if defined(SUNXI_SYSCFG_DEBUG_REG) || defined(CONFIG_COMPONENTS_PM) || defined(CONFIG_STANDBY)
static struct audio_reg_label sunxi_reg_labels[] = {
	REG_LABEL(SUNXI_AUDIO_PATH_HDMIRX_CTRL),
	REG_LABEL_END,
};
#endif

static const char * const i2s2_rx_src[] = {"GPIO", "I2S-TX-OF-HDMIRX"};
static const char * const owa_rx_src[] = {"GPIO", "OWA-TX-OF-HDMIRX"};

static struct snd_kcontrol sunxi_syscfg_controls[] = {
	SND_CTL_ENUM("I2S2 RX SRC SEL", ARRAY_SIZE(i2s2_rx_src),
				i2s2_rx_src, SUNXI_AUDIO_PATH_HDMIRX_CTRL, I2S_RX_SRC_SEL),
	SND_CTL_ENUM("OWA RX SRC SEL", ARRAY_SIZE(owa_rx_src),
				owa_rx_src, SUNXI_AUDIO_PATH_HDMIRX_CTRL, OWA_RX_SRC_SEL),
    SND_CTL_KCONTROL("OWA TX TO HDMIRX", SUNXI_AUDIO_PATH_HDMIRX_CTRL,
                     OWA_TX_TO_HDMIRX_EN, 1),
    SND_CTL_KCONTROL("OWA TX TO GPIO", SUNXI_AUDIO_PATH_HDMIRX_CTRL,
                     OWA_TX_TO_GPIO_EN, 1),
};

#endif /* __SYSCFG_SUN251IW1_H_ */
