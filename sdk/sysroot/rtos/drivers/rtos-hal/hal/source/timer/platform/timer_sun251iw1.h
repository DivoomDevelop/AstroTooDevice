#ifndef __TMR_SUN251IW1_H__
#define __TMR_SUN251IW1_H__

#include <hal_clk.h>

#define SUNXI_SYS_TIMER_NUM			2
#define SUNXI_R_TIMER_NUM			4
#define TIMER_MAX_NUM 				6
#define SUNXI_SYS_TIMER_BASE		0x02050000
#define SUNXI_R_TIMER_BASE			0x07020000

#define SUNXI_R_TIMER_BGR_BASE		0x0701011c
#define SUNXI_R_TIMER_BGR_ENABLE	(1 << 0) | (1 << 16)
#define AHBS_CFG_REG				0x07010000
#define APBS0_CFG_REG				0x0701000c

#define TIMER_APB_CLK_TYPE AW_PRCM_CCU
#define TIMER_APB1_CLK CLK_PRCM_R_APB0_TIMER

#define SUNXI_SYS_GIC_START 75
#define SUNXI_R_GIC_START 	156

#define TIMER_CLK_FROM_AHB
#define HTIMER_AHB_CLK_TYPE	AW_APP_CCU
#define HTIMER_AHB_CLK	CLK_APP_PSI_AHB

#define SUNXI_TMR_PBASE(id)\
({int base = 0;\
if (id <= (SUNXI_SYS_TIMER_NUM - 1))\
base = SUNXI_SYS_TIMER_BASE;\
else if (id <= (SUNXI_R_TIMER_NUM + SUNXI_SYS_TIMER_NUM - 1))\
base  = SUNXI_R_TIMER_BASE;\
base;\
})

#define SUNXI_IRQ_TMR(id)\
({int bit = 0;\
if (id <= (SUNXI_SYS_TIMER_NUM - 1))\
bit = (SUNXI_SYS_GIC_START + (id));\
else if (id <= (SUNXI_R_TIMER_NUM + SUNXI_SYS_TIMER_NUM - 1))\
bit  = (SUNXI_R_GIC_START + (id) - SUNXI_SYS_TIMER_NUM);\
bit;\
})

#define TIMER_IRQ_EN(id) \
({int bit = 0;\
if (id <= (SUNXI_SYS_TIMER_NUM - 1))\
bit = BIT(id);\
else if (id <= (SUNXI_R_TIMER_NUM + SUNXI_SYS_TIMER_NUM - 1))\
bit = BIT((id - SUNXI_SYS_TIMER_NUM));\
bit;\
})

#define TIMER_IRQ_CLEAR(id)\
({int bit = 0;\
if (id <= (SUNXI_SYS_TIMER_NUM - 1))\
bit = BIT(id);\
else if (id <= (SUNXI_R_TIMER_NUM + SUNXI_SYS_TIMER_NUM - 1))\
bit = BIT((id - SUNXI_SYS_TIMER_NUM));\
bit;\
})

#define TIMER_CTL_REG(id) \
({int bit = 0;\
if (id <= (SUNXI_SYS_TIMER_NUM - 1))\
bit = (SUNXI_SYS_TIMER_BASE + 0x10 * (id) + 0x10);\
else if (id <= (SUNXI_R_TIMER_NUM + SUNXI_SYS_TIMER_NUM - 1))\
bit = (SUNXI_R_TIMER_BASE + (0x10 * ((id) - SUNXI_SYS_TIMER_NUM)) + 0x10);\
bit;\
})

#define TIMER_INTVAL_REG(id) \
({int bit = 0;\
if (id <= (SUNXI_SYS_TIMER_NUM - 1))\
bit = (SUNXI_SYS_TIMER_BASE + 0x10 * (id) + 0x14);\
else if (id <= (SUNXI_R_TIMER_NUM + SUNXI_SYS_TIMER_NUM - 1))\
bit = (SUNXI_R_TIMER_BASE + (0x10 * ((id) - SUNXI_SYS_TIMER_NUM)) + 0x14);\
bit;\
})

#define TIMER_CNTVAL_REG(id) \
({int bit = 0;\
if (id <= (SUNXI_SYS_TIMER_NUM - 1))\
bit = (SUNXI_SYS_TIMER_BASE + 0x10 * (id) + 0x18);\
else if (id <= (SUNXI_R_TIMER_NUM + SUNXI_SYS_TIMER_NUM - 1))\
bit = (SUNXI_R_TIMER_BASE + (0x10 * ((id) - SUNXI_SYS_TIMER_NUM)) + 0x18);\
bit;\
})

#define SUNXI_SYS_HTIMER_BASE	0x03008000

enum {
	SUNXI_HTIMER_0 = 0,
	SUNXI_HTIMER_1,
	HTIMER_MAX_NUM
};
#define SUNXI_HTIMER_BASE(id) (SUNXI_SYS_HTIMER_BASE)
#define HTIMER_CTL_REG_OFFSET(id)	(0x20 * (id) + 0x20)
#define HTIMER_INTVAL_LO_REG_OFFSET(id)	(0x20 * (id) + 0x24)
#define HTIMER_INTVAL_HI_REG_OFFSET(id)	(0x20 * (id) + 0x28)
#define HTIMER_CNTVAL_LO_REG_OFFSET(id)	(0x20 * (id) + 0x2c)
#define HTIMER_CNTVAL_HI_REG_OFFSET(id)	(0x20 * (id) + 0x30)
#define PENDING_BIT(id)	BIT(id)
#define HTIMER_IRQ_EN(id)	BIT(id)

#define SUNXI_IRQ_HSTIMER0	71
#define SUNXI_IRQ_HSTIMER1	72

#define SUNXI_AVS_CLK_TYPE AW_APP_CCU
#define SUNXI_AVS_CLK   CLK_APP_BUS_AVS

#define TIMER0_PARAMS \
{	.id = 0, \
	.reg_base = SUNXI_SYS_HTIMER_BASE, \
	.irq_num = SUNXI_IRQ_HSTIMER0, \
	.clk_type = AW_APP_CCU, .clk_id = CLK_APP_BUS_HSTIMER, \
	.bus_type = AW_APP_CCU, .bus_id = CLK_APP_PSI_AHB, \
	.reset_type = AW_APP_CCU, .reset_id = RST_APP_BUS_HSTIME, \
}

#define TIMER1_PARAMS \
{	.id = 1, \
	.reg_base = SUNXI_SYS_HTIMER_BASE, \
	.irq_num = SUNXI_IRQ_HSTIMER1, \
	.clk_type = AW_APP_CCU, .clk_id = CLK_APP_BUS_HSTIMER, \
	.bus_type = AW_APP_CCU, .bus_id = CLK_APP_PSI_AHB, \
	.reset_type = AW_APP_CCU, .reset_id = RST_APP_BUS_HSTIME, \
}

#endif /*__TWI_SUN251IW1_H__  */
