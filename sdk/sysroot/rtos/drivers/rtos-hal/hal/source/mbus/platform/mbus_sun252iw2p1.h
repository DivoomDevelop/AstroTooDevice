#ifndef __MBUS_SUN252IW2P1_H__
#define __MBUS_SUN252IW2P1_H__

typedef struct {
	uint32_t MC_MCGCR;
	uint32_t MC_CPU_BWCR;        // N=0: CPU
	uint32_t MC_RV_SYS_BWCR;     // N=1: RISCV SYS
	uint32_t MC_MAHB_BWCR;       // N=2: MAHB
	uint32_t MC_DMA_BWCR;        // N=3: DMA
	uint32_t MC_VE_BWCR;         // N=4: VE
	uint32_t MC_CE_BWCR;         // N=5: CE
	uint32_t MC_TVD_BWCR;        // N=6: TVD
	uint32_t MC_CSI_BWCR;        // N=7: CSI
	uint32_t MC_DSP_SYS_BWCR;    // N=8: DSP_SYS
	uint32_t MC_G2D_BWCR;        // N=9: G2D
	uint32_t MC_DI_BWCR;         // N=10: DI
	uint32_t MC_DE_BWCR;         // N=11: DE
	uint32_t MC_IOMMU_BWCR;      // N=12: IOMMU
	uint32_t MC_N13_BWCR;        // N=13: Reserved
	uint32_t MC_OTHER_BWCR;
	uint32_t MC_TOTAL_BWCR;
}MBUS_PMU_REGISTER_T;

#define CONFIG_DRIVERS_MBUS_RV_SYS_BW
#define CONFIG_DRIVERS_MBUS_MAHB_BW
#define CONFIG_DRIVERS_MBUS_DMA_BW
#define CONFIG_DRIVERS_MBUS_VE_BW
#define CONFIG_DRIVERS_MBUS_CE_BW
#define CONFIG_DRIVERS_MBUS_TVD_BW
#define CONFIG_DRIVERS_MBUS_CSI_BW
#define CONFIG_DRIVERS_MBUS_DSP_SYS_BW
#define CONFIG_DRIVERS_MBUS_G2D_BW
#define CONFIG_DRIVERS_MBUS_DI_BW
#define CONFIG_DRIVERS_MBUS_DE_BW
#define CONFIG_DRIVERS_MBUS_IOMMU_BW

#define MBUS_CTRL_BASE  0x03102000
#define MBUS_PMU_BASE   (MBUS_CTRL_BASE + 0x009c)

#define MBUS_PMU        ((MBUS_PMU_REGISTER_T *)(MBUS_PMU_BASE))

#define MBUS_MSC_BASE   (MBUS_CTRL_BASE + 0x0210)
#define MBUS_MASTER_COUNT	(40)

#define MBUS_BWLR_BASE   (MBUS_CTRL_BASE + 0x0218)
#endif