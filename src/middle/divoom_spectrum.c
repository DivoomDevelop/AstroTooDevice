/* 本地音乐和电台都使用第 1～64 个 RFFT 频带及同一幅度曲线。 */
static uint32 spectrum_bin_gain(const int32 *fft_buf, int32 bin)
{
    uint32 real = (uint32)fft_buf[bin * 2];
    uint32 imag = (uint32)fft_buf[bin * 2 + 1];
    uint32 magnitude = spectrum_isqrt32(real * real + imag * imag);
    uint32 power = spectrum_log_compress(magnitude);
    uint32 gain = (uint32)(((uint64)power * SPECTRUM_GAIN_TIMES10 * DIV10_Q16) >> 16);
    return gain > SPECTRUM_POWER_MAX ? SPECTRUM_POWER_MAX : gain;
}

