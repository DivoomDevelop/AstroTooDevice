static void process_spectrum_result(SpectrumContext *sptct)
{
	int i;
	int32 *fft_buf = sptct->fft_buf;
	uint32 *smooth_buf = sptct->spectrum_smooth_buf;
	const uint32 smooth_alpha = (uint32)SPECTRUM_SMOOTH_ALPHA_TIMES10;
	const uint32 smooth_inv = 10u - smooth_alpha;

	for (i = 0; i < SPECTRUM_BIN_MAX_LEN; i++) {
		uint32 a = spectrum_bin_gain(fft_buf, i + 1);
		uint32 prev, sm, lv;
		prev = smooth_buf[i];
		sm = ((smooth_alpha * prev + smooth_inv * a) * DIV10_Q16) >> 16;
		smooth_buf[i] = sm;
		lv = (sm * LV_SCALE_MUSIC_Q16) >> 16;
		sptct->step_table[i] = (uint8)(lv > SPECTRUM_FFT_MAX_VALUE ? SPECTRUM_FFT_MAX_VALUE : lv);
	}
	spectrum_levels_store(sptct->step_table, SPECTRUM_BIN_MAX_LEN);
}

static void spectrum_pack_array(const int16 *pcm, uint16 frames, int channels, int sample_step)
{
	int i, off = gSpectrumHandle->cache_size;
	int32 *p_fft = &gSpectrumHandle->fft_buf[off];
	const int32 *p_win = &spectrum_hannin_talbe[off];

	if (sample_step <= 0)
		sample_step = 1;
	if (channels == 2) {
		int in = 0;
		int step2 = sample_step * 2;
		for (i = 0; i < frames; i++, in += step2) {
			int32 v = (int32)((pcm[in] + pcm[in + 1]) >> 1);
			if (v > 0x7FFF)
				v = 0x7FFF;
			else if (v < -0x7FFF)
				v = -0x7FFF;
			p_fft[i] = (v * (int32)p_win[i]) >> 15;
		}
	} else {
		int in = 0;
		for (i = 0; i < frames; i++, in += sample_step) {
			int32 v = (int32)pcm[in];
			if (v > 0x7FFF)
				v = 0x7FFF;
			else if (v < -0x7FFF)
				v = -0x7FFF;
			p_fft[i] = (v * (int32)p_win[i]) >> 15;
		}
	}
}

static void spectrum_ensure(void)
{
	if (gSpectrumHandle)
		return;
	gSpectrumHandle = (SpectrumContext *)divoom_system_malloc(sizeof(SpectrumContext));
	if (gSpectrumHandle)
		memset(gSpectrumHandle, 0, sizeof(SpectrumContext));
}

void divoom_spectrum_process(const int16 *pcm, uint16 frames, int channels, int sample_rate)
{
	SpectrumContext *sptct;
	uint32 effective_dots = frames;
	int sample_step = 1;
	int cache_size;

	(void)sample_rate;
	if (!s_spectrum_local_on || !pcm || frames == 0)
		return;
#if (SPECTRUM_INPUT_RATE_44K_TO_22K)
	effective_dots = frames / 2u;
	sample_step = 2;
#endif
	spectrum_ensure();
	sptct = gSpectrumHandle;
	if (!sptct || !pcm)
		return;
	cache_size = sptct->cache_size;
	if (effective_dots >= SPECTRUM_FFT_MAX_LEN) {
		uint32 remaining;

		sptct->cache_size = 0;
		spectrum_pack_array(pcm, (uint16)SPECTRUM_FFT_MAX_LEN, channels, sample_step);
		if (divoom_fft_rfft((int32 *)sptct->fft_buf, SPECTRUM_FFT_MAX_LEN, 1) == 1)
			process_spectrum_result(sptct);
		remaining = effective_dots - SPECTRUM_FFT_MAX_LEN;
		if (remaining > 0) {
			spectrum_pack_array(&pcm[SPECTRUM_FFT_MAX_LEN * sample_step * channels],
					    (uint16)remaining, channels, sample_step);
			sptct->cache_size = (int)remaining;
		} else {
			sptct->cache_size = 0;
		}
	} else if (cache_size + (int)effective_dots >= SPECTRUM_FFT_MAX_LEN) {
		uint32 need = (uint32)(SPECTRUM_FFT_MAX_LEN - cache_size);
		uint32 remaining;

		spectrum_pack_array(pcm, (uint16)need, channels, sample_step);
		if (divoom_fft_rfft((int32 *)sptct->fft_buf, SPECTRUM_FFT_MAX_LEN, 1) == 1)
			process_spectrum_result(sptct);
		remaining = effective_dots - need;
		if (remaining > 0) {
#if (SPECTRUM_OVERLAP_50PCT)
			memcpy(sptct->fft_buf, sptct->fft_buf + SPECTRUM_OVERLAP_LEN,
			       SPECTRUM_OVERLAP_LEN * sizeof(sptct->fft_buf[0]));
			spectrum_pack_array(&pcm[need * sample_step * channels],
					    (uint16)remaining, channels, sample_step);
			sptct->cache_size = SPECTRUM_OVERLAP_LEN + (int)remaining;
#else
			spectrum_pack_array(&pcm[need * sample_step * channels],
					    (uint16)remaining, channels, sample_step);
			sptct->cache_size = (int)remaining;
#endif
		} else {
			sptct->cache_size = 0;
		}
	} else {
		spectrum_pack_array(pcm, (uint16)effective_dots, channels, sample_step);
		sptct->cache_size += (int)effective_dots;
	}
}

void divoom_spectrum_init(void)
{
	spectrum_ensure();
}

void divoom_spectrum_exit(void)
{
	divoom_spectrum_set_local(0);
	if (gSpectrumHandle) {
		divoom_system_free(gSpectrumHandle);
		gSpectrumHandle = NULL;
	}
}

void divoom_spectrum_set_local(int on)
{
	spectrum_ensure();
	s_spectrum_local_on = on ? 1 : 0;
	if (gSpectrumHandle) {
		gSpectrumHandle->cache_size = 0;
		memset(gSpectrumHandle->spectrum_smooth_buf, 0, sizeof(gSpectrumHandle->spectrum_smooth_buf));
		memset(gSpectrumHandle->step_table, 0, sizeof(gSpectrumHandle->step_table));
	}
	if (!s_spectrum_local_on) {
		memset(s_levels, 0, sizeof(s_levels));
		s_level_count = 0;
		s_level_update_ms = divoom_system_get_tickms();
	}
}

void divoom_spectrum_update_from_jl(const uint8 *levels, int n)
{
	if (s_spectrum_local_on)
		return;
	if (!levels || n <= 0) {
		s_level_count = 0;
		return;
	}
	spectrum_levels_store(levels, n);
}

void divoom_spectrum_reset(void)
{
	memset(s_levels, 0, sizeof(s_levels));
	s_level_count = 0;
	s_level_update_ms = 0;
}

int divoom_spectrum_read_levels(int32_t out[DIVOOM_SPECTRUM_BAND_NUM], int silence_ms)
{
    int count = spectrum_read_radio(out, silence_ms);
    if (count >= 0)
    {
        return count;
    }
    count = s_level_count;
    uint32_t update_ms = s_level_update_ms;
    if (divoom_btcore_uart_cmd_mic_fft_suppressed() || count <= 0 || update_ms == 0u)
    {
        return 0;
    }
    if (silence_ms <= 0)
    {
        silence_ms = DIVOOM_SPECTRUM_SILENCE_MS_DEFAULT;
    }
    if (divoom_system_get_tickms() - update_ms > (uint32_t)silence_ms)
    {
        return 0;
    }
    if (out != NULL)
    {
        memcpy(out, s_levels, (size_t)count * sizeof(*out));
    }
    return count;
}

int divoom_spectrum_is_active(int silence_ms)
{
    return divoom_spectrum_read_levels(NULL, silence_ms) > 0;
}

int divoom_spectrum_has_signal(int silence_ms)
{
    int32_t levels[DIVOOM_SPECTRUM_BAND_NUM];
    int count = divoom_spectrum_read_levels(levels, silence_ms);
    for (int i = 0; i < count; i++)
    {
        if (levels[i] > 0)
        {
            return 1;
        }
    }
    return 0;
}

void divoom_spectrum_get_levels(int32_t out[DIVOOM_SPECTRUM_BAND_NUM])
{
	if (!out)
		return;
    int radio_count = spectrum_read_radio(out, 0);
    if (radio_count >= 0)
    {
        if (radio_count == 0)
        {
            memset(out, 0, sizeof(s_levels));
        }
        return;
    }
	if (divoom_btcore_uart_cmd_mic_fft_suppressed()) {
		memset(out, 0, sizeof(int32_t) * DIVOOM_SPECTRUM_BAND_NUM);
		return;
	}
	memcpy(out, s_levels, sizeof(s_levels));
}

int divoom_spectrum_get_count(void)
{
    int radio_count = spectrum_read_radio(NULL, 0);
    return radio_count >= 0 ? radio_count : s_level_count;
}

int divoom_spectrum_fill(uint8 *out, int count, int step, int max)
{
	int i;
    int32_t radio_levels[DIVOOM_SPECTRUM_BAND_NUM];

	if (!out || count <= 0)
		return 0;
    /* 一次读出当前音源的快照，电台不会覆盖本地音乐或 JL 缓存。 */
    int level_count = spectrum_read_radio(radio_levels, 0);
    const int32_t *levels = radio_levels;
    if (level_count < 0)
    {
        if (divoom_btcore_uart_cmd_mic_fft_suppressed())
        {
            return 0;
        }
        level_count = s_level_count;
        levels = s_levels;
    }
    if (level_count <= 0)
    {
        return 0;
    }
	if (step <= 0)
		step = 1;
	for (i = 0; i < count; i++) {
		int idx = i * step;
		int v = 0;

		if (idx < level_count)
			v = (int)levels[idx];
		if (v < 0)
			v = 0;
		if (v > max)
			v = max;
		out[i] = (uint8)v;
	}
	return 1;
}
