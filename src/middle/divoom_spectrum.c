static inline uint32 spectrum_isqrt32(uint32 x)
{
	uint32 clz;
	uint32 temp;
	uint32 z;
	int i;

	if (x == 0)
		return 0;
	if (x < 4096)
		return spectrum_sqrt_table[x];
	clz = 0;
	temp = x;
	while ((temp & 0x80000000) == 0 && clz < 32) {
		clz++;
		temp <<= 1;
	}
	z = 1u << ((31 - clz) >> 1);
	for (i = 0; i < 3; i++)
		z = (z + x / z) >> 1;
	return z;
}

static inline uint32 spectrum_log_compress(uint32 mag)
{
	uint32 idx;

	if (mag == 0)
		return 0;
	idx = (mag * 100u) / SPECTRUM_POWER_MAX;
	if (idx > 100u)
		idx = 100u;
	return (uint32)spectrum_log_table[idx] * SPECTRUM_POWER_MAX / 100u;
}

