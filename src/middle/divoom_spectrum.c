static void spectrum_levels_store(const uint8 *levels, int n)
{
	int i;

	if (n > DIVOOM_SPECTRUM_BAND_NUM)
		n = DIVOOM_SPECTRUM_BAND_NUM;
	for (i = 0; i < n; i++) {
		int32_t v = (int32_t)levels[i];

		if (v > DIVOOM_SPECTRUM_LEVEL_MAX)
			v = DIVOOM_SPECTRUM_LEVEL_MAX;
		s_levels[i] = v;
	}
	for (; i < DIVOOM_SPECTRUM_BAND_NUM; i++)
		s_levels[i] = 0;
	s_level_count = n;
	s_level_update_ms = divoom_system_get_tickms();
}
